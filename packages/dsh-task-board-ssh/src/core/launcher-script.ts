/**
 * The remote launcher, as text.
 *
 * One POSIX `sh` script, installed once per dsh-ssh host and re-entered for
 * every verb; the state directory it works in is derived at run time, so this
 * text carries no per-host value. It is a line array rather than a template
 * literal so the shell quoting below stays literal: nothing in this file is
 * interpolated by the bundler.
 *
 * @module dsh-task-board-ssh/core/launcher-script
 */

/** Remote launcher source; the POSIX `sh` program the provider installs. */
export const LAUNCHER_SCRIPT: string = [
  "#!/bin/sh",
  "# Remote launcher for the task board SSH provider. POSIX sh only: no bash, no",
  "# tmux and no systemd, because none of the three is guaranteed on a host the",
  "# provider reaches over dsh-ssh.",
  "#",
  "# Verbs: start <runId>, status <runId>, tail <runId> <offset> [limit], stderr <runId> [limit], cancel <runId>.",
  "# __exec is internal: the detached wrapper re-enters this file with it.",
  "#",
  "# State lives under $TASK_BOARD_SSH_STATE (default $HOME/.dsh/task-board-ssh),",
  "# one directory per run under runs/<runId>/. The provider writes spec.json,",
  "# cmd.sh, cwd and prompt.txt there; this script writes stdout.log, stderr.log,",
  "# pid, exit and cancelled. It never parses spec.json: the command line it runs",
  "# is cmd.sh, already quoted by the provider.",
  "#",
  "# Every verb prints one line of key=value pairs on stdout (tail/stderr print raw",
  "# bytes), so the caller parses without a JSON reader on this side.",
  "set -f",
  "",
  "STATE=${TASK_BOARD_SSH_STATE:-$HOME/.dsh/task-board-ssh}",
  "RUNS=$STATE/runs",
  "",
  "die() {",
  "  printf '%s\\n' \"$1\" >&2",
  "  exit \"$2\"",
  "}",
  "",
  "sleep_tick() {",
  "  sleep 0.05 2>/dev/null || sleep 1",
  "}",
  "",
  "valid_run_id() {",
  "  case $1 in",
  "    ''|.|..) return 1 ;;",
  "    *[!A-Za-z0-9._-]*) return 1 ;;",
  "  esac",
  "  return 0",
  "}",
  "",
  "alive() {",
  "  case $1 in",
  "    ''|*[!0-9]*) return 1 ;;",
  "  esac",
  "  kill -0 \"$1\" 2>/dev/null",
  "}",
  "",
  "read_pid() {",
  "  [ -f \"$1/pid\" ] || return 1",
  "  cat \"$1/pid\"",
  "}",
  "",
  "log_bytes() {",
  "  if [ -f \"$1/stdout.log\" ]; then",
  "    wc -c < \"$1/stdout.log\" | tr -d ' '",
  "  else",
  "    printf 0",
  "  fi",
  "}",
  "",
  "print_status() {",
  "  dir=$1",
  "  bytes=$(log_bytes \"$dir\")",
  "  if [ -f \"$dir/exit\" ]; then",
  "    code=$(cat \"$dir/exit\")",
  "    if [ -f \"$dir/cancelled\" ]; then",
  "      printf 'state=cancelled exit=%s bytes=%s\\n' \"$code\" \"$bytes\"",
  "    else",
  "      printf 'state=exited exit=%s bytes=%s\\n' \"$code\" \"$bytes\"",
  "    fi",
  "    return 0",
  "  fi",
  "  pid=$(read_pid \"$dir\" 2>/dev/null || printf '')",
  "  if alive \"$pid\"; then",
  "    printf 'state=running pid=%s bytes=%s\\n' \"$pid\" \"$bytes\"",
  "  else",
  "    printf 'state=lost bytes=%s\\n' \"$bytes\"",
  "  fi",
  "}",
  "",
  "record_exit() {",
  "  printf '%s\\n' \"$1\" > \"$dir/exit\"",
  "}",
  "",
  "run_exec() {",
  "  dir=$1",
  "  trap 'record_exit 143; exit 143' TERM",
  "  trap 'record_exit 130; exit 130' INT",
  "  trap 'record_exit 129; exit 129' HUP",
  "  printf '%s\\n' \"$$\" > \"$dir/pid\"",
  "  if [ -f \"$dir/cancelled\" ]; then",
  "    record_exit 143",
  "    exit 143",
  "  fi",
  "  cwd=$dir",
  "  if [ -f \"$dir/cwd\" ]; then",
  "    cwd=$(cat \"$dir/cwd\")",
  "  fi",
  "  cd \"$cwd\" 2>/dev/null || { record_exit 125; exit 125; }",
  "  sh \"$dir/cmd.sh\" < /dev/null",
  "  code=$?",
  "  record_exit \"$code\"",
  "  exit \"$code\"",
  "}",
  "",
  "wait_for_pid() {",
  "  i=0",
  "  while [ ! -s \"$1/pid\" ] && [ ! -f \"$1/exit\" ]; do",
  "    i=$((i + 1))",
  "    if [ \"$i\" -gt 200 ]; then",
  "      return 1",
  "    fi",
  "    sleep_tick",
  "  done",
  "  return 0",
  "}",
  "",
  "report_running() {",
  "  printf 'state=running pid=%s bytes=%s started=%s\\n' \"$1\" \"$(log_bytes \"$2\")\" \"$3\"",
  "}",
  "",
  "run_start() {",
  "  run_id=$1",
  "  dir=$RUNS/$run_id",
  "  mkdir -p \"$dir\" || die 'cannot create the run directory' 74",
  "  # A run that already recorded its exit is finished: start never reopens it.",
  "  if [ -f \"$dir/exit\" ]; then",
  "    print_status \"$dir\"",
  "    return 0",
  "  fi",
  "  if [ -f \"$dir/cancelled\" ]; then",
  "    record_exit 143",
  "    print_status \"$dir\"",
  "    return 0",
  "  fi",
  "  pid=$(read_pid \"$dir\" 2>/dev/null || printf '')",
  "  if alive \"$pid\"; then",
  "    report_running \"$pid\" \"$dir\" 0",
  "    return 0",
  "  fi",
  "  # The lock closes the window between the liveness check and the recorded",
  "  # pid, so two starts of one runId never produce two agents. Re-checking",
  "  # inside the lock prevents a racing/replayed starter from truncating logs",
  "  # or spawning a duplicate once the first starter releases its lock.",
  "  if mkdir \"$dir/lock\" 2>/dev/null; then",
  "    trap 'rmdir \"$dir/lock\" 2>/dev/null' EXIT",
  "    if [ -f \"$dir/exit\" ]; then",
  "      print_status \"$dir\"",
  "      return 0",
  "    fi",
  "    if [ -f \"$dir/cancelled\" ]; then",
  "      record_exit 143",
  "      print_status \"$dir\"",
  "      return 0",
  "    fi",
  "    pid=$(read_pid \"$dir\" 2>/dev/null || printf '')",
  "    if alive \"$pid\"; then",
  "      report_running \"$pid\" \"$dir\" 0",
  "      return 0",
  "    fi",
  "    rm -f \"$dir/exit\" \"$dir/pid\"",
  "    : > \"$dir/stdout.log\"",
  "    : > \"$dir/stderr.log\"",
  "    if command -v setsid >/dev/null 2>&1; then",
  "      setsid nohup sh \"$0\" __exec \"$dir\" >> \"$dir/stdout.log\" 2>> \"$dir/stderr.log\" < /dev/null &",
  "    else",
  "      nohup sh \"$0\" __exec \"$dir\" >> \"$dir/stdout.log\" 2>> \"$dir/stderr.log\" < /dev/null &",
  "    fi",
  "    wait_for_pid \"$dir\"",
  "    if [ -f \"$dir/exit\" ]; then",
  "      print_status \"$dir\"",
  "      return 0",
  "    fi",
  "    pid=$(read_pid \"$dir\" 2>/dev/null || printf '')",
  "    if alive \"$pid\"; then",
  "      report_running \"$pid\" \"$dir\" 1",
  "      return 0",
  "    fi",
  "    printf 'state=lost started=0\\n'",
  "    return 0",
  "  fi",
  "  wait_for_pid \"$dir\"",
  "  if [ -f \"$dir/exit\" ]; then",
  "    print_status \"$dir\"",
  "    return 0",
  "  fi",
  "  pid=$(read_pid \"$dir\" 2>/dev/null || printf '')",
  "  if alive \"$pid\"; then",
  "    report_running \"$pid\" \"$dir\" 0",
  "    return 0",
  "  fi",
  "  printf 'state=lost started=0\\n'",
  "}",
  "",
  "run_status() {",
  "  dir=$RUNS/$1",
  "  if [ ! -d \"$dir\" ]; then",
  "    printf 'state=missing\\n'",
  "    return 0",
  "  fi",
  "  print_status \"$dir\"",
  "}",
  "",
  "run_tail() {",
  "  dir=$RUNS/$1",
  "  offset=$2",
  "  limit=${3:-}",
  "  case $offset in",
  "    ''|*[!0-9]*) die 'offset must be a byte count' 65 ;;",
  "  esac",
  "  if [ -n \"$limit\" ]; then",
  "    case $limit in",
  "      *[!0-9]*) die 'limit must be a byte count' 65 ;;",
  "    esac",
  "  fi",
  "  if [ ! -f \"$dir/stdout.log\" ]; then",
  "    return 0",
  "  fi",
  "  if [ -n \"$limit\" ]; then",
  "    tail -c +$((offset + 1)) \"$dir/stdout.log\" | head -c \"$limit\"",
  "  else",
  "    tail -c +$((offset + 1)) \"$dir/stdout.log\"",
  "  fi",
  "}",
  "",
  "run_stderr() {",
  "  dir=$RUNS/$1",
  "  limit=${2:-4096}",
  "  case $limit in",
  "    ''|*[!0-9]*) die 'limit must be a byte count' 65 ;;",
  "  esac",
  "  if [ ! -f \"$dir/stderr.log\" ]; then",
  "    return 0",
  "  fi",
  "  tail -c \"$limit\" \"$dir/stderr.log\"",
  "}",
  "",
  "run_cancel() {",
  "  dir=$RUNS/$1",
  "  if [ ! -d \"$dir\" ]; then",
  "    printf 'state=missing\\n'",
  "    return 0",
  "  fi",
  "  # Mark cancellation before checking pid so a racing start or __exec sees it",
  "  # and aborts cleanly without breaking an active start lock.",
  "  : > \"$dir/cancelled\"",
  "  pid=$(read_pid \"$dir\" 2>/dev/null || printf '')",
  "  if ! alive \"$pid\"; then",
  "    if [ -f \"$dir/exit\" ]; then",
  "      print_status \"$dir\"",
  "      return 0",
  "    fi",
  "    printf 'state=not-running\\n'",
  "    return 0",
  "  fi",
  "  kill -s TERM -- \"-$pid\" 2>/dev/null || kill -s TERM \"$pid\" 2>/dev/null",
  "  i=0",
  "  while alive \"$pid\"; do",
  "    i=$((i + 1))",
  "    if [ \"$i\" -gt 100 ]; then",
  "      kill -s KILL -- \"-$pid\" 2>/dev/null || kill -s KILL \"$pid\" 2>/dev/null",
  "      if [ ! -f \"$dir/exit\" ]; then",
  "        printf '%s\\n' 137 > \"$dir/exit\"",
  "      fi",
  "      break",
  "    fi",
  "    sleep_tick",
  "  done",
  "  if [ ! -f \"$dir/exit\" ]; then",
  "    printf '%s\\n' 143 > \"$dir/exit\"",
  "  fi",
  "  printf 'state=cancelled pid=%s\\n' \"$pid\"",
  "}",
  "",
  "verb=${1:-}",
  "run_id=${2:-}",
  "case $verb in",
  "  start|status|tail|stderr|cancel)",
  "    valid_run_id \"$run_id\" || die 'run id must be letters, digits, dots, underscores or hyphens' 65",
  "    ;;",
  "  __exec)",
  "    dir=${2:-}",
  "    [ -n \"$dir\" ] || die 'missing run directory' 64",
  "    run_exec \"$dir\"",
  "    exit 0",
  "    ;;",
  "  *)",
  "    printf 'usage: %s start|status|tail|stderr|cancel <runId> [offset] [limit]\\n' \"$0\" >&2",
  "    exit 64",
  "    ;;",
  "esac",
  "",
  "case $verb in",
  "  start) run_start \"$run_id\" ;;",
  "  status) run_status \"$run_id\" ;;",
  "  tail) run_tail \"$run_id\" \"${3:-0}\" \"${4:-}\" ;;",
  "  stderr) run_stderr \"$run_id\" \"${3:-4096}\" ;;",
  "  cancel) run_cancel \"$run_id\" ;;",
  "esac",
  "",
].join('\n')
