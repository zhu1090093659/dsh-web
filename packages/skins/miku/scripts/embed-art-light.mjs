/**
 * embed-art-light.mjs — inline the light-theme backdrop art as a base64 data
 * URL into `src/client/art-light.ts`, so the skin carries no static assets.
 *
 * Usage: node scripts/embed-art-light.mjs <imagePath>
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const SRC_DIR = dirname(fileURLToPath(import.meta.url))
const OUT_FILE = join(SRC_DIR, '..', 'src', 'client', 'art-light.ts')
const SRC_IMAGE = process.argv[2]
if (!SRC_IMAGE) {
  process.stderr.write('usage: node scripts/embed-art-light.mjs <imagePath>\n')
  process.exit(1)
}

const base64 = readFileSync(SRC_IMAGE).toString('base64')
const out = `/**
 * art-light.ts - GENERATED by scripts/embed-art-light.mjs; do not edit by hand.
 * The light-theme backdrop art - the user-provided image
 * (inlined losslessly as a data URL so the skin carries no static assets).
 * The dark theme keeps MIKU_ART; apply() picks the artwork per theme and
 * layers the matching readability scrim.
 */
export const MIKU_ART_LIGHT = 'data:image/jpeg;base64,${base64}'
`
writeFileSync(OUT_FILE, out)
process.stdout.write(`wrote ${OUT_FILE} (${Math.round(out.length / 1024)} KiB)\n`)
