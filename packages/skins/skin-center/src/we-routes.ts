/**
 * Scene extraction cache format version, embedded in every frames/videos
 * cache key. The cache keys used to be path + mtime only, so an extraction
 * pipeline change (the #751 projection crop, the #761 TEXI rect crop)
 * never invalidated frames generated by an older build — users who had
 * viewed a wallpaper before the upgrade kept being served the stale frame
 * forever (#792). Bump this whenever the extractor output may change; old
 * cache files then miss, regenerate under the new key, and get pruned.
 */
export const SCENE_EXTRACTOR_VERSION = 2

/**
 * Delete same-wallpaper cache files left by earlier extractor versions or
 * older mtimes, so a version bump does not leave stale debris growing the
 * cache directory forever. The stem comparison is exact: the trailing
 * `[_vN_]<mtime>.<ext>` suffix is stripped first, so one base64url path
 * never prunes another (base64url output can itself contain underscores).
 */
function pruneStaleSceneCache(cacheDir: string, base: string, keep: string): void {
  let entries: string[]
  try { entries = readdirSync(cacheDir) } catch { /* unreadable or absent: nothing to prune */ return }
  for (const name of entries) {
    if (name === keep) continue
    const stem = name.replace(/_(?:v\d+_)?\d+\.[a-z0-9]+$/i, '')
    if (stem === base) {
      try { rmSync(joinPath(cacheDir, name), { force: true }) } catch { /* best effort */ }
    }
  }
}

/**
 * Read a web wallpaper's project.json property defaults so the shim can
 * deliver them like WE does on startup. Values pass through raw: colors stay
 * 'r g b' strings, sliders numbers, checkboxes booleans — exactly what the
 * web API hands to applyUserProperties.
 */
function webPropertyDefaults(projectRoot: string): Record<string, { value: unknown }> {
  const out: Record<string, { value: unknown }> = {}
  try {
    const raw = readFileSync(joinPath(projectRoot, 'project.json'), 'utf8')
    const props = (JSON.parse(raw) as { general?: { properties?: Record<string, { value?: unknown }> } })
      .general?.properties
    if (props) {
      for (const [key, def] of Object.entries(props)) {
        if (def && typeof def === 'object' && 'value' in def) out[key] = { value: def.value }
      }
    }
  } catch { /* no project.json or unreadable: empty defaults */ }
  return out
}

