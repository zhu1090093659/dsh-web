#!/usr/bin/env node
/**
 * Generate the reviewed hooks hash registry used to recover legacy Workshop
 * skin installs that predate dsh-market.provenance.json.
 *
 * Usage:
 *   node scripts/skin-hooks-registry.mjs
 *   node scripts/skin-hooks-registry.mjs --check
 */

import { createHash } from 'node:crypto'
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SKINS_DIR = join(ROOT, 'packages', 'skins', 'skin-center', 'skins')
const DEST = join(ROOT, 'packages', 'skins', 'skin-center', 'src', 'reviewed-hooks.generated.ts')
const CHECK = process.argv.includes('--check')

function sha256(bytes) {
  return createHash('sha256').update(bytes).digest('hex')
}

function registryRows() {
  const rows = []
  for (const name of readdirSync(SKINS_DIR).sort()) {
    const dir = join(SKINS_DIR, name)
    let manifestText
    try {
      manifestText = readFileSync(join(dir, 'skin.json'), 'utf8')
    } catch {
      continue
    }
    const manifest = JSON.parse(manifestText)
    const entry = manifest?.facets?.client?.entry
    if (typeof entry !== 'string') continue
    rows.push({
      id: manifest.id,
      entry,
      manifestSha256: sha256(manifestText),
      hooksSha256: sha256(readFileSync(join(dir, ...entry.split('/')))),
    })
  }
  return rows
}

function render(rows) {
  return [
    '/**',
    ' * GENERATED by scripts/skin-hooks-registry.mjs — do not edit.',
    ' * Reviewed market skin hook identities for legacy install recovery.',
    ' */',
    'export interface ReviewedSkinHooksIdentity {',
    '  readonly entry: string',
    '  readonly manifestSha256: string',
    '  readonly hooksSha256: string',
    '}',
    '',
    'export const REVIEWED_SKIN_HOOKS: Readonly<Record<string, ReviewedSkinHooksIdentity>> = {',
    ...rows.flatMap((row) => [
      '  ' + JSON.stringify(row.id) + ': {',
      '    entry: ' + JSON.stringify(row.entry) + ',',
      '    manifestSha256: ' + JSON.stringify(row.manifestSha256) + ',',
      '    hooksSha256: ' + JSON.stringify(row.hooksSha256) + ',',
      '  },',
    ]),
    '}',
    '',
  ].join('\n')
}

const expected = render(registryRows())
if (CHECK) {
  let actual = ''
  try { actual = readFileSync(DEST, 'utf8') } catch { /* missing is drift */ }
  if (actual !== expected) {
    console.error('skin-hooks-registry: generated registry is stale; run node scripts/skin-hooks-registry.mjs')
    process.exit(1)
  }
  console.log('skin-hooks-registry: check OK')
} else {
  writeFileSync(DEST, expected)
  console.log('skin-hooks-registry: wrote reviewed hook identities')
}
